package io.github.jriiik.seedfinder.bedrock;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import io.github.jriiik.seedfinder.Fixtures;
import io.github.jriiik.seedfinder.version.MinecraftVersion;
import io.github.jriiik.seedfinder.version.VersionData;
import java.util.List;
import java.util.Map;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.params.ParameterizedClass;
import org.junit.jupiter.params.provider.MethodSource;

/** Compares our bedrock with the bedrock of chunks generated by each supported Minecraft version itself. */
@ParameterizedClass
@MethodSource("io.github.jriiik.seedfinder.Fixtures#versions")
class BedrockPatternTest {

    private final VersionData data;
    private final JsonObject chunks;

    BedrockPatternTest(MinecraftVersion version) {
        data = version.data();
        chunks = Fixtures.load(version, "bedrock.json");
    }

    @Test
    void bedrockOfRealChunksMatches() {
        int blocks = 0;
        int bedrock = 0;
        for (Map.Entry<String, JsonElement> seedEntry : chunks.getAsJsonObject("seeds").entrySet()) {
            long seed = Long.parseLong(seedEntry.getKey());
            for (Map.Entry<String, JsonElement> dimensionEntry : seedEntry.getValue().getAsJsonObject().entrySet()) {
                BedrockPattern pattern = new BedrockPattern(data.bedrock().get(dimensionEntry.getKey()), seed);
                for (Map.Entry<String, JsonElement> chunkEntry : dimensionEntry.getValue().getAsJsonObject().entrySet()) {
                    String[] chunk = chunkEntry.getKey().split(",");
                    int minX = Integer.parseInt(chunk[0]) * 16;
                    int minZ = Integer.parseInt(chunk[1]) * 16;
                    for (Map.Entry<String, JsonElement> layer : chunkEntry.getValue().getAsJsonObject().entrySet()) {
                        int y = Integer.parseInt(layer.getKey());
                        String[] rows = layer.getValue().getAsString().split(" ");
                        assertEquals(16, rows.length);
                        for (int dz = 0; dz < 16; dz++) {
                            int bits = Integer.parseInt(rows[dz], 16);
                            for (int dx = 0; dx < 16; dx++) {
                                boolean expected = (bits >> dx & 1) != 0;
                                assertEquals(expected, pattern.isBedrock(minX + dx, y, minZ + dz), () -> "seed " + seed + " "
                                    + dimensionEntry.getKey() + " chunk " + chunkEntry.getKey() + " y=" + y);
                                blocks++;
                                bedrock += expected ? 1 : 0;
                            }
                        }
                    }
                }
            }
        }
        // 10 seeds, 4 chunks, 6 overworld layers + 12 nether layers of 256 blocks.
        assertEquals(10 * 4 * 18 * 256, blocks);
        assertTrue(bedrock > blocks / 3 && bedrock < blocks * 2 / 3, bedrock + " of " + blocks);
    }

    @Test
    void rulesComeFromTheGame() {
        BedrockDimension overworld = data.bedrockDimension("overworld").orElseThrow();
        assertEquals(List.of(new BedrockRule("minecraft:bedrock_floor", -64, -59, false)), overworld.rules());
        assertTrue(overworld.dependsOnFullSeed());
        BedrockDimension nether = data.bedrockDimension("nether").orElseThrow();
        assertEquals(2, nether.rules().size());
        assertFalse(nether.dependsOnFullSeed());
        assertEquals(nether, data.bedrockDimension("minecraft:the_nether").orElseThrow());
        assertTrue(data.bedrockDimension("end").orElseThrow().rules().isEmpty());
        assertTrue(data.bedrockDimension("moon").isEmpty());
    }

    /** The integer threshold must give exactly the game's {@code nextFloat() < probability} for every possible draw. */
    @Test
    void thresholdIsExactlyTheGamesFloatTest() {
        for (BedrockDimension dimension : data.bedrock().values()) {
            for (BedrockRule rule : dimension.rules()) {
                for (int y = rule.trueAtAndBelow() + 1; y < rule.falseAtAndAbove(); y++) {
                    double probability = rule.probability(y);
                    int threshold = rule.threshold(y);
                    for (int k = 0; k < BedrockRule.FLOAT_STEPS; k++) {
                        if ((k * 0x1.0p-24f < probability) != (k < threshold)) {
                            throw new AssertionError(rule + " y=" + y + " k=" + k);
                        }
                    }
                }
            }
        }
        BedrockRule floor = data.bedrockDimension("overworld").orElseThrow().floor().orElseThrow();
        assertEquals(List.of(13421773, 10066330, 6710887, 3355444),
            List.of(floor.threshold(-63), floor.threshold(-62), floor.threshold(-61), floor.threshold(-60)));
    }

    @Test
    void overworldBedrockDependsOnAllBitsNetherOnlyOnTheStructureSeed() {
        long seed = 12345L;
        long sameStructureSeed = seed + (0xABCDL << 48);
        BedrockPattern overworldA = new BedrockPattern(data.bedrockDimension("overworld").orElseThrow(), seed);
        BedrockPattern overworldB = new BedrockPattern(data.bedrockDimension("overworld").orElseThrow(), sameStructureSeed);
        BedrockPattern netherA = new BedrockPattern(data.bedrockDimension("nether").orElseThrow(), seed);
        BedrockPattern netherB = new BedrockPattern(data.bedrockDimension("nether").orElseThrow(), sameStructureSeed);
        int overworldDifferent = 0;
        for (int x = 0; x < 32; x++) {
            for (int z = 0; z < 32; z++) {
                overworldDifferent += overworldA.floorTop(x, z) != overworldB.floorTop(x, z) ? 1 : 0;
                assertEquals(netherA.floorTop(x, z), netherB.floorTop(x, z));
            }
        }
        assertTrue(overworldDifferent > 300, overworldDifferent + " of 1024 columns differ");
    }

    @Test
    void thereIsNoBedrockOutsideTheGeneratedWorld() {
        BedrockPattern nether = new BedrockPattern(data.bedrockDimension("nether").orElseThrow(), 12345L);
        BedrockPattern overworld = new BedrockPattern(data.bedrockDimension("overworld").orElseThrow(), 12345L);
        for (int x = 0; x < 16; x++) {
            assertTrue(nether.isBedrock(x, 127, 0), "the nether roof");
            assertFalse(nether.isBedrock(x, 128, 0), "air above the nether roof (checked in real chunks during the review)");
            assertFalse(nether.isBedrock(x, -1, 0));
            assertFalse(overworld.isBedrock(x, -65, 0));
        }
    }

    @Test
    void floorTopIsTheHighestBedrockBlock() {
        BedrockPattern pattern = new BedrockPattern(data.bedrockDimension("overworld").orElseThrow(), 8091867987493326313L);
        for (int x = -20; x < 20; x++) {
            for (int z = -20; z < 20; z++) {
                int top = pattern.floorTop(x, z);
                assertTrue(top >= -64 && top <= -60);
                assertTrue(pattern.isBedrock(x, top, z));
                for (int y = top + 1; y <= -59; y++) {
                    assertFalse(pattern.isBedrock(x, y, z));
                }
            }
        }
    }
}
