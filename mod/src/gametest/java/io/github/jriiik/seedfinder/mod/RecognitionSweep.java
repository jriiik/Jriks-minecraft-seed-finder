package io.github.jriiik.seedfinder.mod;

import io.github.jriiik.seedfinder.recognize.BlockView;
import io.github.jriiik.seedfinder.recognize.RecognizedStarts;
import io.github.jriiik.seedfinder.recognize.RigidKind;
import io.github.jriiik.seedfinder.recognize.RigidRecognizer;
import io.github.jriiik.seedfinder.recognize.RigidTracker;
import io.github.jriiik.seedfinder.recognize.StartPieceRecognizer;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.HashSet;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.TreeMap;
import net.minecraft.core.BlockPos;
import net.minecraft.core.Registry;
import net.minecraft.core.SectionPos;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.core.registries.Registries;
import net.minecraft.resources.Identifier;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.world.level.ChunkPos;
import net.minecraft.world.level.block.Block;
import net.minecraft.world.level.chunk.LevelChunk;
import net.minecraft.world.level.chunk.LevelChunkSection;
import net.minecraft.world.level.chunk.status.ChunkStatus;
import net.minecraft.world.level.levelgen.structure.Structure;
import net.minecraft.world.level.levelgen.structure.StructureSet;
import net.minecraft.world.level.levelgen.structure.placement.RandomSpreadStructurePlacement;

/**
 * The recognizers against many real structures, in every test run: the starts of the recognized sets nearest to the
 * world's centre, each with the chunks around it fully generated by the game (terrain, structures, decoration).
 * Everything recognized is compared with the game's own records. Runs on the server thread.
 */
final class RecognitionSweep {

    /**
     * Starts per structure set, how far out (in placement regions) to look for them, and how far for a set with no
     * start that near (sets of rare biomes, e.g. desert pyramids for the test seed).
     */
    private static final int STARTS_PER_SET = 4;
    private static final int MAX_REGIONS = 5;
    private static final int FAR_REGIONS = 15;
    /** Chunks generated around each start (a piece never reaches further than 3 chunks from its start chunk). */
    private static final int RADIUS = 3;

    /** What a sweep found; {@code sets} are the structure sets that had real starts in it. */
    record Result(int real, int found, List<String> wrong, List<String> missed, List<String> conflicting, Map<String, Integer> pieces,
                  Set<String> sets) {
    }

    private RecognitionSweep() {
    }

    static Result run(ServerLevel level, StartPieceRecognizer recognizer) {
        Registry<StructureSet> sets = level.registryAccess().lookupOrThrow(Registries.STRUCTURE_SET);
        Set<RecognizedStarts.Start> real = new LinkedHashSet<>();
        for (String set : StartPieceLibrary.SETS) {
            real.addAll(nearestStarts(level, set, sets.getValue(Identifier.withDefaultNamespace(set))));
        }

        Set<Block> anchors = new HashSet<>();
        recognizer.anchorBlocks().forEach(id -> BuiltInRegistries.BLOCK.getOptional(Identifier.parse(id)).ifPresent(anchors::add));
        Set<Long> window = new LinkedHashSet<>();
        for (RecognizedStarts.Start start : real) {
            for (int dx = -RADIUS; dx <= RADIUS; dx++) {
                for (int dz = -RADIUS; dz <= RADIUS; dz++) {
                    window.add(ChunkPos.pack(start.chunkX() + dx, start.chunkZ() + dz));
                }
            }
        }
        BlockView view = new BlockView() {
            private final BlockPos.MutableBlockPos pos = new BlockPos.MutableBlockPos();

            @Override
            public boolean isLoaded(int chunkX, int chunkZ) {
                return window.contains(ChunkPos.pack(chunkX, chunkZ));
            }

            @Override
            public String blockAt(int x, int y, int z) {
                return BuiltInRegistries.BLOCK.getKey(level.getChunk(x >> 4, z >> 4).getBlockState(pos.set(x, y, z)).getBlock()).toString();
            }
        };

        RecognizedStarts found = new RecognizedStarts();
        Set<StartPieceRecognizer.Candidate> seen = new HashSet<>();
        Map<String, Integer> pieces = new TreeMap<>();
        for (long packed : window) {
            LevelChunk chunk = level.getChunk(ChunkPos.getX(packed), ChunkPos.getZ(packed));
            LevelChunkSection[] sections = chunk.getSections();
            for (int index = 0; index < sections.length; index++) {
                LevelChunkSection section = sections[index];
                if (section.hasOnlyAir() || !section.maybeHas(state -> anchors.contains(state.getBlock()))) {
                    continue;
                }
                int minY = SectionPos.sectionToBlockCoord(chunk.getSectionYFromSectionIndex(index));
                for (int i = 0; i < 4096; i++) {
                    Block block = section.getBlockState(i & 15, i >> 8, (i >> 4) & 15).getBlock();
                    if (!anchors.contains(block)) {
                        continue;
                    }
                    String id = BuiltInRegistries.BLOCK.getKey(block).toString();
                    for (StartPieceRecognizer.Candidate candidate : recognizer.candidates(id, chunk.getPos().getMinBlockX() + (i & 15), minY + (i >> 8),
                        chunk.getPos().getMinBlockZ() + ((i >> 4) & 15))) {
                        if (seen.add(candidate) && recognizer.check(candidate, view).verdict() == StartPieceRecognizer.Verdict.MATCH) {
                            found.add(candidate);
                            pieces.merge(candidate.piece().name() + " " + candidate.rotation(), 1, Integer::sum);
                        }
                    }
                }
            }
        }

        List<String> wrong = new ArrayList<>();
        for (RecognizedStarts.Start start : found.starts()) {
            if (!real.contains(start) && !isRealStart(level, start)) {
                wrong.add(start.toString());
            }
        }
        List<String> missed = real.stream().filter(start -> !found.starts().contains(start)).map(Object::toString).toList();
        List<String> conflicting = found.conflicting().stream().map(Object::toString).toList();
        return new Result(real.size(), real.size() - missed.size(), wrong, missed, conflicting, pieces, setsOf(real));
    }

    /**
     * The rigid-structure recognizer the way the mod runs it (a {@link RigidTracker} fed chunk by chunk) on the starts of
     * every rigid set that appears in this dimension, with the chunks within the tracker's reach of each generated.
     */
    static Result runRigid(ServerLevel level, RigidRecognizer recognizer, boolean nether) {
        Registry<StructureSet> sets = level.registryAccess().lookupOrThrow(Registries.STRUCTURE_SET);
        Set<RecognizedStarts.Start> real = new LinkedHashSet<>();
        for (RigidKind kind : recognizer.kinds()) {
            real.addAll(nearestStarts(level, kind.structureSet(), sets.getValue(Identifier.withDefaultNamespace(kind.structureSet()))));
        }
        RigidTracker tracker = new RigidTracker(recognizer, nether);
        Set<Long> window = new LinkedHashSet<>();
        for (RecognizedStarts.Start start : real) {
            for (int dx = -tracker.reach(); dx <= tracker.reach(); dx++) {
                for (int dz = -tracker.reach(); dz <= tracker.reach(); dz++) {
                    window.add(ChunkPos.pack(start.chunkX() + dx, start.chunkZ() + dz));
                }
            }
        }
        BlockView view = new BlockView() {
            private final BlockPos.MutableBlockPos pos = new BlockPos.MutableBlockPos();

            @Override
            public boolean isLoaded(int chunkX, int chunkZ) {
                return window.contains(ChunkPos.pack(chunkX, chunkZ));
            }

            @Override
            public String blockAt(int x, int y, int z) {
                if (!isLoaded(x >> 4, z >> 4) || level.isOutsideBuildHeight(y)) {
                    return null;
                }
                return BuiltInRegistries.BLOCK.getKey(level.getChunk(x >> 4, z >> 4).getBlockState(pos.set(x, y, z)).getBlock()).toString();
            }

            @Override
            public String biomeAt(int x, int y, int z) {
                if (!isLoaded(x >> 4, z >> 4)) {
                    return null;
                }
                return level.getNoiseBiome(x >> 2, y >> 2, z >> 2).unwrapKey().map(key -> key.identifier().toString()).orElse(null);
            }
        };
        Map<Block, Integer> classes = new java.util.IdentityHashMap<>();
        for (long packed : window) {
            LevelChunk chunk = level.getChunk(ChunkPos.getX(packed), ChunkPos.getZ(packed));
            List<Integer> found = new ArrayList<>();
            LevelChunkSection[] sections = chunk.getSections();
            for (int index = 0; index < sections.length; index++) {
                LevelChunkSection section = sections[index];
                if (section.hasOnlyAir() || !section.maybeHas(state -> triggerClass(recognizer, classes, state.getBlock()) >= 0)) {
                    continue;
                }
                int minY = SectionPos.sectionToBlockCoord(chunk.getSectionYFromSectionIndex(index));
                for (int i = 0; i < 4096; i++) {
                    int triggerClass = triggerClass(recognizer, classes, section.getBlockState(i & 15, i >> 8, (i >> 4) & 15).getBlock());
                    if (triggerClass >= 0) {
                        found.add(RigidRecognizer.pack(i & 15, minY + (i >> 8), (i >> 4) & 15, triggerClass));
                    }
                }
            }
            tracker.chunkScanned(chunk.getPos().x(), chunk.getPos().z(), found.stream().mapToInt(Integer::intValue).toArray());
        }
        RecognizedStarts found = new RecognizedStarts();
        Map<String, Integer> layouts = new TreeMap<>();
        for (int calls = 0; calls < 10_000 && (calls == 0 || tracker.pendingCount() > 0); calls++) {
            for (RigidRecognizer.Detection d : tracker.work(view, () -> false)) {
                found.add(d.kind().structureSet(), recognizer.rules(d.kind()).spacing(), d.chunkX(), d.chunkZ());
                layouts.merge(d.layout().variant(), 1, Integer::sum);
            }
        }
        List<String> wrong = new ArrayList<>();
        for (RecognizedStarts.Start start : found.starts()) {
            if (!real.contains(start) && !isRealStart(level, start)) {
                wrong.add(start.toString());
            }
        }
        List<String> missed = real.stream().filter(start -> !found.starts().contains(start)).map(Object::toString).toList();
        List<String> conflicting = found.conflicting().stream().map(Object::toString).toList();
        return new Result(real.size(), real.size() - missed.size(), wrong, missed, conflicting, layouts, setsOf(real));
    }

    private static int triggerClass(RigidRecognizer recognizer, Map<Block, Integer> classes, Block block) {
        return classes.computeIfAbsent(block, key -> recognizer.triggerClass(BuiltInRegistries.BLOCK.getKey(key).toString()));
    }

    /** The real starts of a set nearest to the world's centre, from the game's own records. */
    private static List<RecognizedStarts.Start> nearestStarts(ServerLevel level, String set, StructureSet structureSet) {
        RandomSpreadStructurePlacement placement = (RandomSpreadStructurePlacement) structureSet.placement();
        List<int[]> regions = new ArrayList<>();
        for (int rx = -FAR_REGIONS; rx <= FAR_REGIONS; rx++) {
            for (int rz = -FAR_REGIONS; rz <= FAR_REGIONS; rz++) {
                regions.add(new int[] {rx, rz});
            }
        }
        regions.sort(Comparator.comparingInt(region -> region[0] * region[0] + region[1] * region[1]));
        List<RecognizedStarts.Start> starts = new ArrayList<>();
        for (int[] region : regions) {
            if (!starts.isEmpty() && Math.max(Math.abs(region[0]), Math.abs(region[1])) > MAX_REGIONS) {
                break;
            }
            ChunkPos chunk = placement.getPotentialStructureChunk(level.getSeed(), region[0] * placement.spacing(), region[1] * placement.spacing());
            RecognizedStarts.Start start = new RecognizedStarts.Start(set, chunk.x(), chunk.z());
            if (isRealStart(level, start)) {
                starts.add(start);
                if (starts.size() == STARTS_PER_SET) {
                    break;
                }
            }
        }
        return starts;
    }

    private static Set<String> setsOf(Set<RecognizedStarts.Start> starts) {
        Set<String> sets = new java.util.TreeSet<>();
        starts.forEach(start -> sets.add(start.structureSet()));
        return sets;
    }

    private static boolean isRealStart(ServerLevel level, RecognizedStarts.Start start) {
        Registry<Structure> structures = level.registryAccess().lookupOrThrow(Registries.STRUCTURE);
        Set<String> inSet = new HashSet<>();
        SeedFinderClient.data().structureSet(start.structureSet()).orElseThrow().structures().forEach(entry -> inSet.add(entry.structure()));
        return level.getChunk(start.chunkX(), start.chunkZ(), ChunkStatus.STRUCTURE_STARTS, true).getAllStarts().entrySet().stream()
            .anyMatch(entry -> entry.getValue().isValid() && inSet.contains(String.valueOf(structures.getKey(entry.getKey()))));
    }
}
